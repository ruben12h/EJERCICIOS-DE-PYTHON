#Guarda en una variable el número Pi (3.1416) y calcula el perímetro de un círculo de radio 7.

pi = 3.1416                                                      # valor del Pi

radio = 7                                                        # radio del circulo

perimetro = 2 * pi * radio                                       # cálculo del perímetro

print(f"El perímetro del circulo es : {perimetro}")                     # mostrar resultado

